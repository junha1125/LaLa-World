"""Parity validation for the modern-mujoco PointMaze port (point_maze_env.py).

Uses the raw dataset the training pairs were built from
($LALA_DATA_ROOT/sim_raw/point_maze: states/actions .pth + obses/episode_NNN.pth)
as ground truth generated by the original d4rl+mujoco-py stack.

Checks:
1. physics  — one-step: from every GT state, apply the GT action, compare the next state.
              rollout: replay all actions from the initial state, track divergence.
2. calibrate — fit the free-camera lookat/distance so rendered maze walls align with
              the dataset frames (differential, iterated on the wall bounding box).
3. render   — pixel diff between our render of GT states and the stored frames,
              with the dataset's own frame-to-frame diff as the noise floor.

Run: python -m evals.lala_world.point_maze_env.validate [--calibrate] [--episodes N]
"""

import argparse
import json
import os

import numpy as np
import torch
from PIL import Image

from evals.lala_world.point_maze_env import MazeEnv

DATA = os.path.join(os.environ.get("LALA_DATA_ROOT", "data"), "sim_raw", "point_maze")
OUT_DEFAULT = "logs/planning/point_maze_port_validation"


def load_states_actions():
    states = torch.load(f"{DATA}/states.pth", map_location="cpu").numpy()
    actions = torch.load(f"{DATA}/actions.pth", map_location="cpu").numpy()
    return states, actions


def load_frames(episode):
    return torch.load(f"{DATA}/obses/episode_{episode:03d}.pth", map_location="cpu").numpy()


def make_raw_env(render=False):
    env = MazeEnv(reward_type="sparse", reset_target=False)
    if render:
        env.prepare_for_render()
    env.seed(0)
    return env


def one_step_errors(env, states, actions, episodes, horizon):
    errs = []
    for i in episodes:
        for t in range(horizon):
            env.set_state(states[i, t, :2], states[i, t, 2:4])
            _, _, _, info = env.step(actions[i, t])
            errs.append(info["state"][:4] - states[i, t + 1])
    return np.asarray(errs)


def rollout_divergence(env, states, actions, episodes, horizon):
    pos_div = np.zeros((len(episodes), horizon))
    for k, i in enumerate(episodes):
        env.set_init_state(states[i, 0].copy())
        env.reset()
        for t in range(horizon):
            _, _, _, info = env.step(actions[i, t])
            pos_div[k, t] = np.linalg.norm(info["state"][:2] - states[i, t + 1, :2])
    return pos_div


def wall_bbox(img):
    """Bounding box of the tan maze walls (color mask)."""
    r = img[..., 0].astype(int)
    g = img[..., 1].astype(int)
    b = img[..., 2].astype(int)
    mask = (r > b + 30) & (r > 120) & (g > b)
    ys, xs = np.where(mask)
    if len(xs) < 100:
        raise RuntimeError("wall mask empty — render badly misaligned or colors off")
    return xs.min(), xs.max(), ys.min(), ys.max()


def ball_center(img):
    """Center of the green agent site; None if not visible."""
    r = img[..., 0].astype(int)
    g = img[..., 1].astype(int)
    b = img[..., 2].astype(int)
    mask = (g > r + 20) & (g > b + 20) & (g > 90)
    ys, xs = np.where(mask)
    if len(xs) < 4:
        return None
    return float(xs.mean()), float(ys.mean())


def render_state(env, state):
    env.set_state(state[:2], state[2:4])
    env.set_marker()
    return env._render_frame()


def calibrate(env, states, iters=6):
    """Iteratively match our wall bbox to the dataset's on episode 0 frame 0."""
    ref = load_frames(0)[0]
    bd = wall_bbox(ref)
    fovy = float(env.model.vis.global_.fovy)
    for it in range(iters):
        img = render_state(env, states[0, 0])
        bo = wall_bbox(img)
        span_o = ((bo[1] - bo[0]) + (bo[3] - bo[2])) / 2.0
        span_d = ((bd[1] - bd[0]) + (bd[3] - bd[2])) / 2.0
        env._cam.distance *= span_o / span_d
        k = 224.0 / (2.0 * env._cam.distance * np.tan(np.deg2rad(fovy / 2.0)))
        du = ((bd[0] + bd[1]) - (bo[0] + bo[1])) / 2.0  # +: ours must move right
        dv = ((bd[2] + bd[3]) - (bo[2] + bo[3])) / 2.0  # +: ours must move down
        env._cam.lookat[0] -= du / k
        env._cam.lookat[1] -= dv / k
        print(
            f"iter {it}: span ours {span_o:.1f} vs dset {span_d:.1f}, shift ({du:+.1f},{dv:+.1f})px "
            f"-> lookat ({env._cam.lookat[0]:.4f}, {env._cam.lookat[1]:.4f}) dist {env._cam.distance:.4f}"
        )
    img = render_state(env, states[0, 0])
    mae = np.abs(img.astype(float) - ref.astype(float)).mean()
    print(f"calibrated: CAM_LOOKAT = ({env._cam.lookat[0]:.4f}, {env._cam.lookat[1]:.4f}, 0.0)")
    print(f"calibrated: CAM_DISTANCE = {env._cam.distance:.4f}")
    print(f"frame MAE after calibration: {mae:.2f}")
    return img, ref


def render_parity(env, states, episodes, frames_per_ep, out_dir):
    maes, over20, ball_px = [], [], []
    floor = []
    for i in episodes:
        ref_frames = load_frames(i)
        ts = np.linspace(0, ref_frames.shape[0] - 2, frames_per_ep).astype(int)
        for t in ts:
            img = render_state(env, states[i, t])
            ref = ref_frames[t]
            diff = np.abs(img.astype(float) - ref.astype(float))
            maes.append(diff.mean())
            over20.append((diff.max(axis=-1) > 20).mean())
            floor.append(np.abs(ref_frames[t].astype(float) - ref_frames[t + 1].astype(float)).mean())
            bo, bd = ball_center(img), ball_center(ref)
            if bo is not None and bd is not None:
                ball_px.append(float(np.hypot(bo[0] - bd[0], bo[1] - bd[1])))
            if t == ts[0]:
                side = np.concatenate([ref, img, np.clip(diff * 4, 0, 255).astype(np.uint8)], axis=1)
                Image.fromarray(side).save(os.path.join(out_dir, f"compare_ep{i:03d}_t{t:02d}.png"))
    return {
        "mae_mean": float(np.mean(maes)),
        "mae_max": float(np.max(maes)),
        "frac_px_over20_mean": float(np.mean(over20)),
        "ball_center_dist_px_mean": float(np.mean(ball_px)),
        "ball_center_dist_px_max": float(np.max(ball_px)),
        "dset_frame_to_frame_mae_floor": float(np.mean(floor)),
        "n_frames": len(maes),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--episodes", type=int, default=20, help="episodes for physics checks")
    ap.add_argument("--render-episodes", type=int, default=6)
    ap.add_argument("--frames-per-ep", type=int, default=5)
    ap.add_argument("--horizon", type=int, default=99)
    ap.add_argument("--calibrate", action="store_true", help="only fit camera constants and exit")
    ap.add_argument("--out", default=OUT_DEFAULT)
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)

    states, actions = load_states_actions()

    if args.calibrate:
        env = make_raw_env(render=True)
        img, ref = calibrate(env, states)
        side = np.concatenate([ref, img], axis=1)
        Image.fromarray(side).save(os.path.join(args.out, "calibration_dset_vs_ours.png"))
        return

    rng = np.random.default_rng(0)
    eps = rng.choice(states.shape[0], size=args.episodes, replace=False)

    env = make_raw_env(render=False)
    errs = one_step_errors(env, states, actions, eps, args.horizon)
    pos_e, vel_e = np.abs(errs[:, :2]), np.abs(errs[:, 2:])
    step_pos_scale = float(np.abs(np.diff(states[eps, :, :2], axis=1)).mean())
    one_step = {
        "pos_abs_err_mean": float(pos_e.mean()),
        "pos_abs_err_p99": float(np.quantile(pos_e, 0.99)),
        "pos_abs_err_max": float(pos_e.max()),
        "vel_abs_err_mean": float(vel_e.mean()),
        "vel_abs_err_p99": float(np.quantile(vel_e, 0.99)),
        "vel_abs_err_max": float(vel_e.max()),
        "dset_mean_abs_pos_change_per_step": step_pos_scale,
        "n_transitions": int(errs.shape[0]),
    }
    print("one-step:", json.dumps(one_step, indent=2))

    pos_div = rollout_divergence(env, states, actions, eps, args.horizon)
    rollout = {
        "final_pos_div_mean": float(pos_div[:, -1].mean()),
        "final_pos_div_max": float(pos_div[:, -1].max()),
        "pos_div_at_t30_mean": float(pos_div[:, 29].mean()),
        "pos_div_mean_over_traj": float(pos_div.mean()),
        "n_episodes": int(pos_div.shape[0]),
    }
    print("rollout:", json.dumps(rollout, indent=2))

    renv = make_raw_env(render=True)
    reps = rng.choice(states.shape[0], size=args.render_episodes, replace=False)
    render = render_parity(renv, states, reps, args.frames_per_ep, args.out)
    print("render:", json.dumps(render, indent=2))

    summary = {"one_step": one_step, "rollout": rollout, "render": render}
    with open(os.path.join(args.out, "summary.json"), "w") as f:
        json.dump(summary, f, indent=2)
    print(f"saved {args.out}/summary.json")


if __name__ == "__main__":
    main()
